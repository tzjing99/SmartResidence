/**
 * Magic-byte sniff of the leading bytes of a file. Returns the detected MIME
 * type (one of the allowed image/document types) or `null` if unrecognized.
 * Defends against Content-Type spoofing — the declared MIME is never trusted
 * on its own. Operates on a plain byte view so it is reusable + unit-testable.
 */
export function sniffMimeType(bytes: Uint8Array): string | null {
  const b = bytes;
  if (b.length < 12) return null;

  // JPEG: FF D8 FF
  if (b[0] === 0xff && b[1] === 0xd8 && b[2] === 0xff) return 'image/jpeg';

  // PNG: 89 50 4E 47 0D 0A 1A 0A
  if (
    b[0] === 0x89 &&
    b[1] === 0x50 &&
    b[2] === 0x4e &&
    b[3] === 0x47 &&
    b[4] === 0x0d &&
    b[5] === 0x0a &&
    b[6] === 0x1a &&
    b[7] === 0x0a
  ) {
    return 'image/png';
  }

  // GIF: "GIF87a" / "GIF89a"
  if (b[0] === 0x47 && b[1] === 0x49 && b[2] === 0x46 && b[3] === 0x38) return 'image/gif';

  // PDF: "%PDF-"
  if (b[0] === 0x25 && b[1] === 0x50 && b[2] === 0x44 && b[3] === 0x46 && b[4] === 0x2d) {
    return 'application/pdf';
  }

  // RIFF....WEBP (WebP)
  if (
    b[0] === 0x52 &&
    b[1] === 0x49 &&
    b[2] === 0x46 &&
    b[3] === 0x46 &&
    b[8] === 0x57 &&
    b[9] === 0x45 &&
    b[10] === 0x42 &&
    b[11] === 0x50
  ) {
    return 'image/webp';
  }

  // ISO-BMFF "ftyp" box (HEIC/HEIF) — brand at bytes 8..12.
  if (b[4] === 0x66 && b[5] === 0x74 && b[6] === 0x79 && b[7] === 0x70) {
    const brand = String.fromCharCode(
      b[8] ?? 0,
      b[9] ?? 0,
      b[10] ?? 0,
      b[11] ?? 0,
    ).toLowerCase();
    const heicBrands = new Set([
      'heic',
      'heix',
      'heim',
      'heis',
      'hevc',
      'hevx',
      'hevm',
      'hevs',
      'mif1',
      'msf1',
    ]);
    if (heicBrands.has(brand)) {
      // mif1/msf1 are generic HEIF containers; report image/heif for those.
      return brand === 'mif1' || brand === 'msf1' ? 'image/heif' : 'image/heic';
    }
  }

  return null;
}

/** HTML `accept` value for native file inputs (web). */
export const IMAGE_ACCEPT_ATTR = 'image/*,.heic,.heif';

/** HTML `accept` value for PDF uploads (announcement attachments). */
export const DOCUMENT_ACCEPT_ATTR = 'application/pdf,.pdf';

export function isAllowedImageMime(mime: string | null | undefined): mime is AllowedImageMimeType {
  if (!mime) return false;
  return (ALLOWED_IMAGE_MIME_TYPES as readonly string[]).includes(mime.toLowerCase());
}

export function isAllowedDocumentMime(
  mime: string | null | undefined,
): mime is AllowedDocumentMimeType {
  if (!mime) return false;
  return (ALLOWED_DOCUMENT_MIME_TYPES as readonly string[]).includes(mime.toLowerCase());
}

export function isHeic(mime: string | null | undefined): boolean {
  if (!mime) return false;
  const m = mime.toLowerCase();
  return m === 'image/heic' || m === 'image/heif';
}

/** Strip path separators / odd characters so the storage key stays clean. */
export function sanitizeFileName(name: string): string {
  const base = name.split(/[\\/]/).pop() ?? name;
  const cleaned = base.replace(/[^A-Za-z0-9._-]+/g, '-').replace(/-+/g, '-');
  const trimmed = cleaned.replace(/^[-.]+/, '').slice(-120);
  return trimmed.length > 0 ? trimmed : 'upload';
}

/** Contract for the presign request body (`POST /api/attachments/presign`). */
export const PresignUploadSchema = z.object({
  contentType: z.string().min(1).max(120),
  fileName: z.string().min(1).max(200),
  size: z.number().int().positive().max(MAX_UPLOAD_BYTES).optional(),
});
export type PresignUploadInput = z.infer<typeof PresignUploadSchema>;

/** Response returned by the presign endpoint. */
export interface PresignUploadResponse {
  url: string;
  fields: Record<string, string>;
  bucket: string;
  key: string;
  expiresIn: number;
  attachmentId: string;
}

/**
 * Response from the multipart upload endpoint (`POST /api/uploads`). The
 * server has already optimized the image + generated a thumbnail; the raw
 * phone photo is never stored.
 */
export interface UploadResponse {
  attachmentId: string;
  key: string;
  thumbnailKey: string | null;
  mimeType: string;
  size: number;
  width: number | null;
  height: number | null;
  status: AttachmentStatus;
  /** Primary delivery format of the (eventual) variant set, e.g. `'avif'`. */
  format: string | null;
  /** Async transcode lifecycle — `PENDING` until the worker finishes. */
  transcodeStatus: TranscodeStatus;
}

/** A successfully uploaded attachment, as referenced by forms/messages. */
export interface UploadedAttachment {
  attachmentId: string;
  key: string;
  thumbnailKey?: string | null;
  mimeType: string;
  size: number;
  width?: number | null;
  height?: number | null;
  /** Local preview URL/URI (object URL on web, file uri on mobile). */
  previewUrl?: string;
  fileName?: string;
}
