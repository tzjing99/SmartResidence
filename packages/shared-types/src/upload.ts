import { z } from 'zod';

/**
 * Image mime types accepted by the upload pipeline.
 *
 * `image/heic` / `image/heif` are included because iOS captures and iCloud
 * library exports are HEIC by default. Mobile clients convert HEIC -> JPEG
 * before upload; web stores the original (iOS Safari already hands us JPEG
 * when picking from the album, desktop HEIC is stored as-is).
 */
export const ALLOWED_IMAGE_MIME_TYPES = [
  'image/jpeg',
  'image/png',
  'image/webp',
  'image/gif',
  'image/heic',
  'image/heif',
] as const;
export type AllowedImageMimeType = (typeof ALLOWED_IMAGE_MIME_TYPES)[number];

/** Maximum size for a single uploaded image (15 MB). */
export const MAX_UPLOAD_BYTES = 15 * 1024 * 1024;

/** Maximum size for a single uploaded PDF document (25 MB). */
export const MAX_DOCUMENT_UPLOAD_BYTES = 25 * 1024 * 1024;

export const ALLOWED_DOCUMENT_MIME_TYPES = ['application/pdf'] as const;
export type AllowedDocumentMimeType = (typeof ALLOWED_DOCUMENT_MIME_TYPES)[number];

/** How many attachments a single message / form may carry. */
export const MAX_ATTACHMENTS_PER_MESSAGE = 6;

/** Max combined size of a single message's attachments (40 MB). */
export const MAX_TOTAL_UPLOAD_BYTES = 40 * 1024 * 1024;

/** Longest edge (px) the optimized full image is downscaled to server-side. */
export const IMAGE_MAX_DIMENSION = 1600;

/** Longest edge (px) of the generated thumbnail derivative. */
export const THUMBNAIL_MAX_DIMENSION = 400;

/** TTL (hours) after which an un-attached (PENDING) upload is swept. */
export const ORPHAN_ATTACHMENT_TTL_HOURS = 24;

/** Lifecycle status of an attachment. */
export type AttachmentStatus = 'PENDING' | 'COMMITTED';

//////////////////////////////////////////////////////////////////////////////
// Output (delivery) formats & transcode pipeline (AVIF + WebP fallback)
//////////////////////////////////////////////////////////////////////////////

/**
 * Delivery image formats the server emits per upload. `avif` is the primary,
 * smallest format; `webp` is the universal fallback for AVIF-incapable clients
 * (pre-16.4 Safari, legacy Android WebView, managed Edge 118–120).
 */
export const OUTPUT_IMAGE_FORMATS = ['avif', 'webp'] as const;
export type OutputImageFormat = (typeof OUTPUT_IMAGE_FORMATS)[number];

/** Primary delivery format requested by capable clients. */
export const DEFAULT_OUTPUT_FORMAT: OutputImageFormat = 'avif';

/** Fallback delivery format served when AVIF is missing / unsupported. */
export const FALLBACK_OUTPUT_FORMAT: OutputImageFormat = 'webp';

/** MIME type for each output format. */
export const OUTPUT_FORMAT_MIME: Record<OutputImageFormat, string> = {
  avif: 'image/avif',
  webp: 'image/webp',
};

export function isOutputImageFormat(v: string | null | undefined): v is OutputImageFormat {
  if (!v) return false;
  return (OUTPUT_IMAGE_FORMATS as readonly string[]).includes(v.toLowerCase());
}

/** The four derivative variants produced per (non-passthrough) image upload. */
export const VARIANT_KINDS = ['displayAvif', 'thumbAvif', 'displayWebp', 'thumbWebp'] as const;
export type VariantKind = (typeof VARIANT_KINDS)[number];

/**
 * Lifecycle of the async (BullMQ) transcode pipeline for an attachment:
 * - `PENDING`  — row created; full variant set still being generated by the worker.
 * - `READY`    — AVIF + WebP variant set generated; original deleted.
 * - `FAILED`   — transcode threw irrecoverably; original (or inline thumb) retained.
 * - `SKIPPED`  — passthrough (GIF) or a decode the host can't handle (HEIC w/o libheif);
 *                original bytes are served as-is.
 */
export const TRANSCODE_STATUSES = ['PENDING', 'READY', 'FAILED', 'SKIPPED'] as const;
export type TranscodeStatus = (typeof TRANSCODE_STATUSES)[number];

